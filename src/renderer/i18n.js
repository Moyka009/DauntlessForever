function watch() {
  if (observer && document.body) observer.observe(document.body, {subtree:true,childList:true,characterData:true});
}
window.DFLocale = {apply,setLanguage,get language(){return language;}};
window.addEventListener('DOMContentLoaded', () => {
  const selector = document.getElementById('launcher-language');
  if (selector) { selector.value = language; selector.addEventListener('change',e => setLanguage(e.target.value)); }
  apply();
  observer = new MutationObserver(mutations => {
    // Process only changed nodes, never rescan the whole application for each update.
    observer.disconnect();
    try {
      for (const m of mutations) {
        if (m.type === 'characterData') translateNode(m.target);
        else for (const node of m.addedNodes) apply(node);
      }
    } finally { watch(); }
  });
  watch();
});
